const CATALOG = { en, ar };

function lookup(obj, path) {
  return path.split(".").reduce((acc, part) => (acc == null ? acc : acc[part]), obj);
}

export function translate(lang, key, vars) {
  let value = lookup(CATALOG[lang], key);
  if (value == null) value = lookup(CATALOG[FALLBACK_LANGUAGE], key);
  if (value == null) return key;
  if (vars) {
    return value.replace(/\{(\w+)\}/g, (m, name) =>
      name in vars ? String(vars[name]) : m
    );
  }
  return value;
}

// Canonical (English, DB-stored) role names → i18n keys. The stored name is
// what the RBAC matrix keys on and must never change; this only affects how a
// role is *displayed*, translated into the active language. Unknown names
// (e.g. a custom role) fall back to the raw name.
const ROLE_KEY = {
  "Super Administrator": "superAdministrator",
  "Business Owner": "businessOwner",
  "General Manager": "generalManager",
  "Branch Manager": "branchManager",
  "Inventory Officer": "inventoryOfficer",
  "Sales Officer": "salesOfficer",
  "Purchasing Officer": "purchasingOfficer",
  "HR Officer": "hrOfficer",
  "CRM Officer": "crmOfficer",
  "Finance Department": "financeDepartment",
  "Chief Financial Officer": "chiefFinancialOfficer",
  "Landing Page Manager": "landingPageManager",
  Viewer: "viewer",
};

export function translateRole(name, t) {
  if (!name) return name;
  const key = ROLE_KEY[name];
  return key ? t(`roles.${key}`) : name;
}
